import 'package:flutter_test/flutter_test.dart';
import 'package:pseudolearn_app/domain/model/export/export_result.dart';
import 'package:pseudolearn_app/domain/model/export/target_language_id.dart';
import 'package:pseudolearn_app/domain/model/profiles/syntax_profile_id.dart';
import 'package:pseudolearn_app/engine/bridge/frb_generated.dart';
import 'package:pseudolearn_app/engine/rust/export/rust_program_exporter.dart';
import 'package:pseudolearn_app/engine/rust/native_rust_transport.dart';
import 'package:pseudolearn_app/engine/rust/rust_transport.dart';

const String _tasks =
    'SubProceso Suspendible Produce(stream Como Canal<Entero>)\n'
    '  Definir firstAccepted Como Logico <- Aguardar stream.Enviar(1);\n'
    '  Si firstAccepted Entonces\n'
    '  FinSi\n'
    '  Definir secondAccepted Como Logico <- Aguardar stream.Enviar(2);\n'
    '  Si secondAccepted Entonces\n'
    '  FinSi\n'
    '  stream.Cerrar();\n'
    'FinSubProceso\n'
    '\n'
    'SubProceso Suspendible Consume(stream Como Canal<Entero>)\n'
    '  Repetir\n'
    '  Segun Aguardar stream.Recibir() Hacer\n'
    '  Algo(receivedValue): Escribir receivedValue;\n'
    '  Nada: Salir;\n'
    '  FinSegun\n'
    '  Hasta Que Falso\n'
    'FinSubProceso\n'
    '\n'
    'Algoritmo P\n'
    '  Definir stream Como Canal<Entero> <- Canal(1);\n'
    '  Tareas\n'
    '  Lanzar Produce(stream);\n'
    '  Lanzar Consume(stream);\n'
    '  FinTareas\n'
    'FinAlgoritmo\n';

const String _network =
    'SubProceso Probe() Como Resultado<Entero, ErrorES>\n'
    'Definir net Como RedCap <- Propagar SolicitarRed();\n'
    'Retornar Exito(1);\n'
    'FinSubProceso\n'
    'Algoritmo Main\n'
    'Segun Probe() Hacer\n'
    'Exito(value): Escribir value;\n'
    'Error(problem): Escribir problem.Codigo;\n'
    'FinSegun\n'
    'FinAlgoritmo\n';

void main() {
  RustTransport? transport;
  late RustProgramExporter exporter;

  setUpAll(() async {
    await initializeNativeBridge();
    transport = openNativeTransport();
    exporter = RustProgramExporter(transport!);
  });

  tearDownAll(() {
    transport?.close();
    RustLib.dispose();
  });

  ExportResult export(
    String source,
    TargetLanguageId target, {
    SyntaxProfileId profile = SyntaxProfileId.classicSpanish,
  }) => exporter.export(
    sourceCode: source,
    targetLanguage: target,
    profileId: profile,
  );

  String code(String source, TargetLanguageId target) =>
      (export(source, target) as ExportSuccess).program.sourceCode;

  test('translates tasks and channels to cooperative Rust tasks', () {
    final rust = code(_tasks, TargetLanguageId.rust);

    expect(rust, startsWith('// Generated by PseudoLearn - Target: Rust'));
    expect(rust, contains('async fn produce(stream: Channel<i64>) {'));
    expect(rust, contains('task_scope.spawn(produce(stream.clone()));'));
    expect(rust, contains('match stream.receive().await {'));
    expect(rust, contains('run_tasks(algorithm());'));
  });

  test('translates tasks and channels to asyncio in Python', () {
    final python = code(_tasks, TargetLanguageId.python);

    expect(python, startsWith('# Generated by PseudoLearn - Target: Python'));
    expect(python, contains('async def produce(stream):'));
    expect(python, contains('case Some(received_value):'));
    expect(python, contains('asyncio.run(main())'));
  });

  test('attributes generated lines to source nodes and the header to none', () {
    final program =
        (export('Algoritmo P\n  Escribir 1;\nFinAlgoritmo\n', TargetLanguageId.rust)
                as ExportSuccess)
            .program;
    final lines = program.sourceCode.split('\n');
    final writeLine = lines.indexWhere((line) => line.contains('println!')) + 1;

    expect(program.lineOrigins.first, isNull);
    expect(program.lineOrigins[writeLine - 1], isNotNull);
    expect(program.linesFor(program.lineOrigins[writeLine - 1]), contains(writeLine));
  });

  test('exports English programs with the profile boolean words', () {
    final python =
        (export(
                  'algorithm P\n  write true;\nendAlgorithm\n',
                  TargetLanguageId.python,
                  profile: SyntaxProfileId.english,
                )
                as ExportSuccess)
            .program
            .sourceCode;

    expect(python, contains('print(boolean_text(True), sep="")'));
    expect(python, contains('return "true" if value else "false"'));
  });

  test('exports an empty algorithm as an empty main', () {
    expect(
      code('Algoritmo P\nFinAlgoritmo\n', TargetLanguageId.python),
      contains('def main():\n    pass'),
    );
    expect(
      code('Algoritmo P\nFinAlgoritmo\n', TargetLanguageId.rust),
      contains('fn main() {\n}'),
    );
  });

  test('names a construct without a standard library equivalent', () {
    final result = export(_network, TargetLanguageId.rust);

    expect(result, isA<ExportUnavailable>());
    final blockers = (result as ExportUnavailable).blockers;
    expect(blockers, isNotEmpty);
    expect(blockers.first.construct, 'capability');
    expect(blockers.first.range.startLine, 2);
  });

  test('reports an analysis error for invalid programs', () {
    for (final target in TargetLanguageId.values) {
      expect(export('Algoritmo P\n', target), isA<ExportAnalysisError>());
      expect(export('', target), isA<ExportAnalysisError>());
    }
  });
}
