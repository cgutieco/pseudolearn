import 'package:flutter_test/flutter_test.dart';
import 'package:pseudolearn_app/domain/model/analysis/program_node_id.dart';
import 'package:pseudolearn_app/domain/model/export/export_result.dart';
import 'package:pseudolearn_app/domain/model/export/target_language_id.dart';
import 'package:pseudolearn_app/domain/model/profiles/syntax_profile_id.dart';
import 'package:pseudolearn_app/engine/bridge/frb_generated.dart';
import 'package:pseudolearn_app/engine/rust/export/rust_program_exporter.dart';
import 'package:pseudolearn_app/engine/rust/native_rust_transport.dart';
import 'package:pseudolearn_app/engine/rust/rust_transport.dart';

const String _rich =
    'Clase Base\n  Metodo Constructor(e Como Entero)\n  FinMetodo\nFinClase\n'
    'Clase Hija Hereda De Base\n  Privado Definir total Como Entero;\n'
    '  Metodo Constructor(e Como Entero)\n    Super.Constructor(e);\n'
    '    Este.total <- e;\n  FinMetodo\n'
    '  Publico Metodo Doble() Como Entero\n    Retornar Este.total * 2;\n'
    '  FinMetodo\nFinClase\n'
    'Funcion Cuadrado(x Como Entero) Como Entero\n  Retornar x ^ 2;\nFinFuncion\n'
    'Proceso P\n  Dimension v[3] Como Entero;\n  Definir h Como Hija <- Nuevo Hija(4);\n'
    '  Definir Mutable r Como Real <- 0.0;\n'
    '  r <- Raiz(Cuadrado(3) + 1.5);\n'
    '  Para i <- 3 Hasta 1 Con Paso -1 Hacer\n'
    '    Escribir v[i], "x" Sin Saltar;\n  FinPara\n'
    '  Segun v[1] Hacer\n    1, 2:\n      Escribir h.Doble();\n'
    '    De Otro Modo:\n      Leer r;\n  FinSegun\n'
    '  Repetir\n    h.Doble();\n  Hasta Que NO (v[1] <> 2 Y Verdadero);\n'
    'FinProceso\n';

const String _expectedPython = '''# Generated by PseudoLearn - Target: Python
import math

class Base:
    def __init__(self, e):
        pass

class Hija(Base):
    def __init__(self, e):
        super().__init__(e)
        self.total = e
    def Doble(self):
        return self.total * 2

def Cuadrado(x):
    return x ** 2

def main():
    v = [0] * (3)
    h = Hija(4)
    r = 0.0
    r = math.sqrt(Cuadrado(3) + 1.5)
    for i in range(3, 1 - 1, -1):
        print(v[i], "x", end="")
    match v[1]:
        case 1 | 2:
            print(h.Doble())
        case _:
            r = input()
    while True:
        h.Doble()
        if not (v[1] != 2 and True):
            break

if __name__ == "__main__":
    main()''';

void main() {
  RustTransport? transport;
  late RustProgramExporter exporter;

  setUpAll(() async {
    await initializeNativeBridge();
    transport = openNativeTransport();
    exporter = RustProgramExporter(transport!);
  });

  tearDownAll(() {
    transport?.close();
    RustLib.dispose();
  });

  ExportResult export(
    String source,
    TargetLanguageId target, {
    SyntaxProfileId profile = SyntaxProfileId.classicSpanish,
  }) => exporter.export(
    sourceCode: source,
    targetLanguage: target,
    profileId: profile,
  );

  test('emits Python for classes, inheritance, builtins, loops and switch', () {
    final result = export(_rich, TargetLanguageId.python);

    expect(result, isA<ExportSuccess>());
    expect((result as ExportSuccess).program.sourceCode, _expectedPython);
  });

  test('emits Rust structs, constructors and statement forms', () {
    final code =
        (export(_rich, TargetLanguageId.rust) as ExportSuccess)
            .program
            .sourceCode;

    expect(code, contains('struct Hija {\n    pub base: Base,\n    pub total: i64,\n}'));
    expect(code, contains('pub fn new(e: i64) -> Self {'));
    expect(code, contains('// Super.Constructor(e);'));
    expect(code, contains('pub fn Doble(&mut self) -> i64 {'));
    expect(code, contains('for i in (1..=3).rev() {'));
    expect(code, contains("print!(\"{} {}\", v[(i) as usize], 'x');"));
    expect(code, contains('match v[(1) as usize] {'));
    expect(code, contains('r = (Cuadrado(3) + 1.5 as f64).sqrt();'));
    expect(code, contains('loop {'));
  });

  test('attributes statement lines to view nodes and headers to none', () {
    final program =
        (export(_rich, TargetLanguageId.python) as ExportSuccess).program;

    expect(program.lineOrigins.first, isNull);
    final attributed = program.lineOrigins.whereType<ProgramNodeId>();
    expect(attributed, isNotEmpty);
    expect(program.linesFor(attributed.first), isNotEmpty);
  });

  test('exports English programs with the same structure', () {
    const source =
        'algorithm Sum\n  define mutable a as integer <- 0;\n  a <- 1;\n  write a;\nendAlgorithm\n';

    final code =
        (export(source, TargetLanguageId.python, profile: SyntaxProfileId.english)
                as ExportSuccess)
            .program
            .sourceCode;

    expect(code, contains('a = 1'));
    expect(code, contains('print(a)'));
  });

  test('exports an empty algorithm as an empty main', () {
    final code =
        (export('Algoritmo P\nFinAlgoritmo\n', TargetLanguageId.python)
                as ExportSuccess)
            .program
            .sourceCode;

    expect(code, contains('def main():\n    pass'));
  });

  test('reports an analysis error for invalid programs', () {
    for (final target in TargetLanguageId.values) {
      expect(export('Algoritmo P\n', target), isA<ExportAnalysisError>());
      expect(export('', target), isA<ExportAnalysisError>());
    }
  });
}
