import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

import '../../tool/check_android_comments.dart';

void main() {
  group('Android comment checker', () {
    late Directory root;

    setUp(() => root = Directory.systemTemp.createTempSync('android_comments_'));
    tearDown(() => root.deleteSync(recursive: true));

    File write(String relative, String content) =>
        File(p.join(root.path, relative))
          ..parent.createSync(recursive: true)
          ..writeAsStringSync(content);

    test('the application android folder carries no comments', () {
      final violations = checkAndroidComments(p.join(Directory.current.path, 'android'));

      expect(violations, isEmpty, reason: violations.join('\n'));
    });

    test('a missing android folder has nothing to report', () {
      expect(checkAndroidComments(p.join(root.path, 'absent')), isEmpty);
    });

    test('an empty android folder has nothing to report', () {
      expect(checkAndroidComments(root.path), isEmpty);
    });

    test('Negative fixture: Kotlin line and block comments are reported', () {
      write('app/Main.kt', 'class Main\n// line\nval x = 1 /* block */\n * continued\n');

      expect(checkAndroidComments(root.path).map((violation) => violation.line), [2, 3, 4]);
    });

    test('Negative fixture: an XML comment is reported with its file', () {
      final file = write('app/src/main/AndroidManifest.xml', '<manifest>\n<!-- note -->\n</manifest>\n');

      expect(checkAndroidComments(root.path).single.path, file.path);
    });

    test('Negative fixture: hash comments in ProGuard and properties are reported', () {
      write('app/proguard-rules.pro', '# keep\n-keep class A\n');
      write('gradle.properties', 'a=b\n  # note\n');

      expect(checkAndroidComments(root.path), hasLength(2));
    });

    test('a URL inside a Gradle string is not a comment', () {
      write('app/build.gradle.kts', 'val url = uri("https://example.com/maven/")\n');

      expect(checkAndroidComments(root.path), isEmpty);
    });

    test('generated and local files are skipped', () {
      write('local.properties', '# generated by flutter\n');
      write('app/src/main/java/GeneratedPluginRegistrant.java', '// generated\n');
      write('.gradle/cache.properties', '# cache\n');
      write('build/output.xml', '<!-- build -->\n');

      expect(checkAndroidComments(root.path), isEmpty);
    });

    test('files without a known comment syntax are ignored', () {
      write('app/src/main/res/mipmap-mdpi/notes.txt', '// not source\n');

      expect(checkAndroidComments(root.path), isEmpty);
    });
  });
}
